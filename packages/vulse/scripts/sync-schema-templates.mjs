// Embeds the repo-root `schema-definitions/*.json` bundles into a generated TS
// module so the package can serve them as built-in templates at runtime (admin
// gallery + CLI) without filesystem access. Mirrors scripts/embed-bridge.mjs.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { dirname, join, basename } from 'node:path'
import { fileURLToPath } from 'node:url'

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = join(pkgRoot, '..', '..')
const sourceDir = join(repoRoot, 'schema-definitions')
const outPath = join(pkgRoot, 'src/core/blueprints/schema-templates.generated.ts')

const files = readdirSync(sourceDir)
  .filter((f) => f.endsWith('.json'))
  .sort()

const templates = files.map((file) => {
  const raw = readFileSync(join(sourceDir, file), 'utf8')
  const bundle = JSON.parse(raw)
  const blueprints = Array.isArray(bundle.blueprints) ? bundle.blueprints : []
  return {
    key: basename(file, '.json'),
    name: typeof bundle.name === 'string' ? bundle.name : basename(file, '.json'),
    description: typeof bundle.description === 'string' ? bundle.description : '',
    handles: blueprints.map((b) => b?.handle).filter((h) => typeof h === 'string'),
    bundle,
  }
})

const body = `// Generated by sync-schema-templates — do not edit.
// Source: schema-definitions/*.json at the repo root.

export interface SchemaTemplate {
  key: string
  name: string
  description: string
  handles: string[]
  bundle: unknown
}

export const SCHEMA_TEMPLATES: SchemaTemplate[] = ${JSON.stringify(templates, null, 2)}
`

writeFileSync(outPath, body)
console.log(`sync-schema-templates: embedded ${templates.length} template(s) -> ${outPath}`)
